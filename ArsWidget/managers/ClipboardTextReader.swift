import Foundation
import AppKit
import UniformTypeIdentifiers

struct ClipboardReadEvent: Codable {
    let kind: String
    var text: String? = nil
    var changeCount: Int? = nil
}

// Shared by the isolated reader and regression tests. No writes, format
// conversion, image decoding or file access is performed here.
final class ClipboardTextReader {
    private let board: NSPasteboard
    private(set) var lastChange: Int
    static let maxItemBytes = 64 * 1024

    init(board: NSPasteboard, previousChangeCount: Int? = nil) {
        self.board = board
        lastChange = previousChangeCount ?? board.changeCount
    }

    func readChange(willRead: (Int) -> Void = { _ in }) -> ClipboardReadEvent {
        let count = board.changeCount
        guard count != lastChange else { return ClipboardReadEvent(kind: "idle") }
        // Attempt each generation once, even when the provider returns nil.
        lastChange = count
        willRead(count)
        guard let types = board.types, board.changeCount == count,
              Self.accepts(types), let items = board.pasteboardItems,
              items.count <= 16 else { return ClipboardReadEvent(kind: "idle") }
        var parts: [String] = []
        var size = 0
        for item in items {
            guard Self.accepts(item.types), let text = item.string(forType: .string),
                  board.changeCount == count else { return ClipboardReadEvent(kind: "idle") }
            size += text.utf8.count + (parts.isEmpty ? 0 : 1)
            guard size <= Self.maxItemBytes else { return ClipboardReadEvent(kind: "idle") }
            parts.append(text)
        }
        let text = parts.joined(separator: "\n")
        guard board.changeCount == count,
              let finalTypes = board.types, Self.accepts(finalTypes),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return ClipboardReadEvent(kind: "idle")
        }
        return ClipboardReadEvent(kind: "text", text: text)
    }

    private static func accepts(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        guard types.contains(.string) else { return false }
        let excluded: Set<String> = [
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
            "de.petermaurer.TransientPasteboardType", "com.apple.pasteboard.promised-file-url"
        ]
        return !types.contains { type in
            if excluded.contains(type.rawValue) || type == .fileURL { return true }
            guard let uti = UTType(type.rawValue) else { return false }
            return uti.conforms(to: .image) || uti.conforms(to: .movie)
                || uti.conforms(to: .audio) || uti.conforms(to: .pdf)
        }
    }
}

enum ClipboardWorker {
    static let argument = "--arswidget-clipboard-reader"

    static var previousChangeCount: Int? {
        guard let index = CommandLine.arguments.firstIndex(of: "--after-change-count"),
              index + 1 < CommandLine.arguments.count else { return nil }
        return Int(CommandLine.arguments[index + 1])
    }

    // This executable has no SwiftUI app, delegates or widget services.
    // The parent owns our stdin pipe: EOF also stops us if the parent is killed.
    static func run(board: NSPasteboard = .general, previousChangeCount: Int? = nil) {
        DispatchQueue.global(qos: .utility).async {
            while !FileHandle.standardInput.availableData.isEmpty {}
            exit(0)
        }
        emit(ClipboardReadEvent(kind: "busy"))
        let reader = ClipboardTextReader(board: board, previousChangeCount: previousChangeCount)
        emit(ClipboardReadEvent(kind: "idle", changeCount: reader.lastChange))
        while true {
            Thread.sleep(forTimeInterval: 0.75)
            autoreleasepool {
                emit(ClipboardReadEvent(kind: "busy"))
                var event = reader.readChange { count in
                    emit(ClipboardReadEvent(kind: "busy", changeCount: count))
                }
                event.changeCount = reader.lastChange
                emit(event)
            }
        }
    }

    static func emit(_ event: ClipboardReadEvent) {
        guard var data = try? JSONEncoder().encode(event) else { return }
        data.append(0x0a)
        FileHandle.standardOutput.write(data)
    }
}
